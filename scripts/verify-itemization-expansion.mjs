import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const jsPath = path.join(root, '_site', 'assets', 'page-F6OuavDb.js');
const cssPath = path.join(root, '_site', 'assets', 'riftbound.css');

if (!fs.existsSync(jsPath) || !fs.existsSync(cssPath)) {
  throw new Error('Itemization verifier: build output is missing. Run scripts/build-site.sh first.');
}

const js = fs.readFileSync(jsPath, 'utf8');
const css = fs.readFileSync(cssPath, 'utf8');

const requireText = (haystack, needle, label) => {
  if (!haystack.includes(needle)) throw new Error(`Itemization verifier: missing ${label}: ${needle}`);
};
const rejectText = (haystack, needle, label) => {
  if (haystack.includes(needle)) throw new Error(`Itemization verifier: stale ${label} is still present: ${needle}`);
};

requireText(js, 'const RIFT_ITEMIZATION_EXPANSION_VERSION=3;', 'itemization runtime version');
requireText(js, 'Itemization Expansion requires exactly 32 new Legendaries', '32-Legendary runtime assertion');
requireText(js, 'RIFT_ITEMIZATION_REWORK_CATALOG(items,add)', 'catalog expansion execution');
requireText(js, 'master-sword-awakened', 'first new Legendary');
requireText(js, 'devil-breaker-overdrive', 'last new Legendary');
requireText(js, 'tags:[`unique`,`buildDefining`,`itemizationExpansion`]', 'new Legendary identity tag');
requireText(js, 'RIFT_STAT_BREAKDOWN', 'base/cap/item/effective stat breakdown');
requireText(js, 'LEVEL-UP CAP ', 'Stat Menu level-up cap language');
requireText(js, 'event.detail>=2', 'stable recipe double-click resolver');
requireText(js, '__RIFT_RECIPE_CLICK_TIMER__', 'delayed component selection guard');
requireText(js, '__RIFT_RECIPE_DBLCLICK__', 'purchase duplicate guard');
rejectText(js, 'DOUBLE-CLICK BUY', 'recipe quick-buy instruction');
rejectText(js, 'DOUBLE-CLICK COMPONENTS', 'Armory quick-buy instruction');
requireText(js, 'function RIFT_ITEM_TOOLTIP', 'hover tooltip component');
requireText(js, 'RIFT_ITEM_ICON=function RIFT_ITEM_ICON', 'designed icon renderer override');
requireText(js, 'art-gemlight', 'maximalist icon layer stack');
requireText(js, 'item.id===`rebellion-devil-greatsword`', 'Rebellion rework exception');
requireText(js, '[`Legendary`,`Mythical`].includes(target.rarity)', 'unique high-rarity recipe ownership guard');
requireText(css, '.item-hover-tooltip', 'hover tooltip styling');
requireText(css, 'Riftbound Item Portrait Overhaul', 'maximalist portrait stylesheet');
requireText(css, '.rift-item-icon.art-blade>.art-main', 'blade silhouette art');
requireText(css, '.rift-item-icon.art-axe>.art-main', 'axe silhouette art');
requireText(css, '.rift-item-icon.art-wand>.art-main', 'wand silhouette art');
requireText(css, '.rift-item-icon.art-ring>.art-main', 'ring silhouette art');
requireText(css, '.rift-item-icon.art-gem>.art-main', 'gem silhouette art');
requireText(css, '.legendary-complete', 'Legendary completion feedback');

// The 32 entries are generated by one runtime loop, so counting the loop-body tag in
// source code is intentionally invalid. The Build Expansion runtime verifier imports
// the production bundle and asserts exactly 32 catalog entries carry this tag. Here we
// independently require all 32 canonical IDs so a missing/replaced entry still fails CI.
const newLegendaryIds = [
  'master-sword-awakened','zangetsu-moonfang','nichirin-sunsteel','leviathan-returning-axe',
  'blades-of-chaos-chain','buster-sword-limit','masamune-long-reach','elder-wand-elder-rule',
  'green-lantern-ring','chaos-emerald-core','sonic-power-sneakers','matrix-red-pill',
  'predator-cloak-module','nanosuit-2','lightsaber-kyber-core','darksaber-mandalore',
  'frostmourne-soulsteel','ashbringer-dawn','hidden-blade-assassin','gravity-gun-zero-point',
  'portal-device-aperture','bfg-argent-core','master-ball-command','necronomicon-ex-mortis',
  'dragon-radar-targeting','witcher-medallion-wolf','pipboy-vats-3000','time-turner-hourglass',
  'black-pearl-compass','berserkers-draupnir','stand-arrow-bow','devil-breaker-overdrive',
];
if (new Set(newLegendaryIds).size !== 32) throw new Error('Itemization verifier: canonical new-Legendary ID list is not exactly 32 unique entries.');
for (const id of newLegendaryIds) requireText(js, `\`${id}\``, `new Legendary ${id}`);

const minimumCatalogNames = [
  'Brute Knuckle', 'Duelist Sensor', 'ODM Harness',
  'Green Lantern Ring', 'Aperture Portal Device', 'Time-Turner Hourglass',
];
for (const name of minimumCatalogNames) requireText(js, name, `catalog item ${name}`);

console.log('Itemization Expansion verified: 32 canonical Legendaries, reliable component double-click purchase, maximalist layered item portraits, hover tooltips, and uncapped item stat display are wired.');
